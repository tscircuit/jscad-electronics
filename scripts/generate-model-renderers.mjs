import { randomUUID } from "node:crypto"
import {
  mkdir,
  readdir,
  readFile,
  rename,
  unlink,
  writeFile,
} from "node:fs/promises"
import { basename, dirname, join, relative, resolve, sep } from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const packageRoot = fileURLToPath(new URL("../", import.meta.url))

/**
 * @typedef {Object} GenerateModelRenderersOptions
 * @property {string} [modelsDir]
 * @property {string} [outputDir]
 * @property {string} [registryModuleSpecifier]
 * @property {"auto" | "bun" | "node"} [discoveryBackend]
 */

/** @param {string} cwd @param {"auto" | "bun" | "node"} backend */
async function discover(cwd, backend) {
  const useBun =
    backend === "bun" || (backend === "auto" && typeof Bun !== "undefined")
  if (useBun) {
    if (typeof Bun === "undefined")
      throw new Error("Bun discovery requires Bun")
    const paths = []
    for await (const path of new Bun.Glob(
      "*/{register.ts,register.tsx,vanilla.ts}",
    ).scan({
      cwd,
      onlyFiles: true,
      dot: false,
      followSymlinks: false,
    }))
      paths.push(path)
    return paths
  }
  const paths = []
  for (const folder of await readdir(cwd, { withFileTypes: true })) {
    if (!folder.isDirectory() || folder.name.startsWith(".")) continue
    for (const file of await readdir(resolve(cwd, folder.name), {
      withFileTypes: true,
    })) {
      if (
        file.isFile() &&
        ["register.ts", "register.tsx", "vanilla.ts"].includes(file.name)
      ) {
        paths.push(join(folder.name, file.name))
      }
    }
  }
  return paths
}

/** @param {string} outputDir @param {string} target */
function moduleSpecifier(outputDir, target) {
  const path = relative(outputDir, target).split(sep).join("/")
  return path.startsWith(".") ? path : "./" + path
}

/** @param {string} file @param {string} source */
async function writeChanged(file, source) {
  try {
    if ((await readFile(file, "utf8")) === source) return false
  } catch (error) {
    if (error.code !== "ENOENT") throw error
  }
  await mkdir(dirname(file), { recursive: true })
  const temporary = file + "." + process.pid + "." + randomUUID() + ".tmp"
  try {
    await writeFile(temporary, source, { flag: "wx" })
    await rename(temporary, file)
  } finally {
    await unlink(temporary).catch((error) => {
      if (error.code !== "ENOENT") throw error
    })
  }
  return true
}

/** @param {GenerateModelRenderersOptions} [options] */
export async function generateModelRenderers(options = {}) {
  const modelsDir = resolve(options.modelsDir ?? packageRoot + "/lib/models")
  const outputDir = resolve(options.outputDir ?? packageRoot + "/lib/generated")
  const paths = await discover(modelsDir, options.discoveryBackend ?? "auto")
  const adapters = new Map()
  const vanillaOverrides = new Set()
  for (const path of paths) {
    const folder = dirname(path)
    if (basename(path) === "vanilla.ts") {
      vanillaOverrides.add(folder)
      continue
    }
    if (adapters.has(folder)) {
      throw new Error("Duplicate renderer registration adapters in " + folder)
    }
    adapters.set(folder, path.replace(/\.tsx?$/, ""))
  }
  if (adapters.size === 0) {
    throw new Error("No renderer registration adapters found in " + modelsDir)
  }
  const modelDirectories = [...adapters.keys()].sort()
  const header =
    "// Generated by scripts/generate-model-renderers.mjs. Do not edit."
  const imports = modelDirectories.flatMap((folder, index) => {
    const path = JSON.stringify(
      moduleSpecifier(outputDir, resolve(modelsDir, adapters.get(folder))),
    )
    return [
      "import { model as model" + index + " } from " + path,
      "import { register as register" + index + " } from " + path,
    ]
  })
  const bootstrap = [
    header,
    "import type { ModelRendererRegistry } from " +
      JSON.stringify(options.registryModuleSpecifier ?? "../model-registry"),
    ...imports,
    "",
    "export const builtinModelRenderers = [\n" +
      modelDirectories.map((_, index) => "  model" + index + ",").join("\n") +
      "\n] as const",
    "",
    "export function registerAllModelRenderers(registry: ModelRendererRegistry): void {",
    ...modelDirectories.map((_, index) => "  register" + index + "(registry)"),
    "}",
    "",
  ].join("\n")
  const exportsFor = (vanilla) =>
    [
      header,
      ...modelDirectories.map((folder) => {
        const target = resolve(
          modelsDir,
          folder,
          vanilla && vanillaOverrides.has(folder) ? "vanilla" : "index",
        )
        return (
          "export * from " + JSON.stringify(moduleSpecifier(outputDir, target))
        )
      }),
      "",
    ].join("\n")
  const sources = {
    "model-renderers.ts": bootstrap,
    "models.ts": exportsFor(false),
    "vanilla-models.ts": exportsFor(true),
  }
  const changedFiles = []
  for (const [filename, source] of Object.entries(sources)) {
    if (await writeChanged(resolve(outputDir, filename), source)) {
      changedFiles.push(filename)
    }
  }
  return { sources, changedFiles, modelDirectories }
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  await generateModelRenderers()
}
